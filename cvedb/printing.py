from collections.abc import Iterable, Iterator
from io import StringIO
import re
from shutil import get_terminal_size, which
from subprocess import PIPE, Popen
import sys
from typing import TextIO
from unicodedata import combining, east_asian_width

from cvedb.cve import CVE, Severity

SEVERITY_COLORS = {
    Severity.UNKNOWN: "\033[34;1m",
    Severity.NONE: "\033[37;1m",
    Severity.LOW: "\033[36;1m",
    Severity.MEDIUM: "\033[33;1m",
    Severity.HIGH: "\033[31;1m",
    Severity.CRITICAL: "\033[35;1m",
}

STRIP_ANSI_REGEX = re.compile(r"\x1b\[[;\d]*[A-Za-z]").sub
CONTROL_ESCAPES = {"\n": r"\n", "\r": r"\r", "\t": r"\t", "\u2028": r"\u2028", "\u2029": r"\u2029"}
RESET = "\033[0m"


def strip_ansi(text: str) -> str:
    """Remove the ANSI styles generated by the renderer."""
    return STRIP_ANSI_REGEX("", text)


def ansi_len(text: str) -> int:
    """Count display columns, excluding ANSI styles and combining marks."""
    return sum(_character_width(character) for character in strip_ansi(text))


def _character_width(character: str) -> int:
    if combining(character):
        return 0
    return 2 if east_asian_width(character) in ("W", "F") else 1


def _escape_text(text: str) -> str:
    result = []
    for character in text:
        number = ord(character)
        if number < 32 or 127 <= number <= 159 or character in ("\u2028", "\u2029"):
            result.append(CONTROL_ESCAPES.get(character, f"\\x{number:02x}"))
        else:
            result.append(character)
    return "".join(result)


def _description(cve: CVE) -> str:
    description = cve.description()
    if description is None:
        description = cve.descriptions[0].value if cve.descriptions else "No description available"
    return _escape_text(description)


def _take_width(text: str, width: int) -> tuple[str, str]:
    columns = 0
    for index, character in enumerate(text):
        columns += _character_width(character)
        if columns > width:
            return text[:index], text[index:]
    return text, ""


def _wrap_text(text: str, width: int, prefix: str, hang_indent: str) -> Iterator[str]:
    indent, _ = _take_width(prefix, max(0, width - 2))
    continuation, _ = _take_width(hang_indent, max(0, width - 2))
    line = indent
    columns = ansi_len(line)
    for character in text:
        character_width = _character_width(character)
        if columns + character_width > width:
            last_space = line.rfind(" ")
            if last_space > len(indent):
                yield line[:last_space]
                line = continuation + line[last_space + 1 :]
            else:
                yield line
                line = continuation
            indent = continuation
            columns = ansi_len(line)
            if columns + character_width > width:
                yield line
                line = continuation
                columns = ansi_len(line)
        line += character
        columns += character_width
    yield line


def _print_box_row(
    stream: TextIO,
    columns: int,
    text: str,
    right_text: str = "",
    *,
    prefix: str = "",
    hang_indent: str = "",
    line_pre: str = "",
    line_post: str = "",
) -> None:
    width = columns - 2
    if right_text:
        gap = width - ansi_len(prefix + text + right_text)
        text += " " * max(1, gap) + right_text
    for line in _wrap_text(text, width, prefix, hang_indent):
        padding = " " * (width - ansi_len(line))
        stream.write(f"║{line_pre}{line}{line_post}{padding}║\n")


def _print_heading(stream: TextIO, columns: int, identifier: str, color: str) -> None:
    padding = columns - 4 - ansi_len(identifier)
    if padding < 0:
        stream.write(f"╔{'═' * (columns - 2)}╗\n")
        _print_box_row(stream, columns, identifier, line_pre=color, line_post=RESET)
    else:
        left = padding // 2
        stream.write(f"╔{'═' * left}╡{color}{identifier}{RESET}╞{'═' * (padding - left)}╗\n")


def _print_divider(stream: TextIO, columns: int) -> None:
    stream.write(f"╟{'─' * (columns - 2)}╢\n")


def _print_metadata(cve: CVE, stream: TextIO, columns: int, color: str) -> None:
    _print_box_row(
        stream,
        columns,
        f" Published: {cve.published_date:%Y-%m-%d}",
        right_text=f"Modified: {cve.last_modified_date:%Y-%m-%d} ",
    )
    score = "????" if cve.impact is None else f"{cve.impact.base_score:02.1f}"
    _print_box_row(
        stream,
        columns,
        f" Severity: {cve.severity.name}",
        right_text=f"Impact: {score} ",
        line_pre=color,
        line_post=RESET,
    )


def _print_references(cve: CVE, stream: TextIO, columns: int) -> None:
    if not cve.references:
        return
    _print_divider(stream, columns)
    _print_box_row(stream, columns, " References", line_pre="\033[4m", line_post=RESET)
    for reference in cve.references:
        if reference.name is not None:
            _print_box_row(
                stream, columns, _escape_text(reference.name), prefix="  • ", hang_indent="    "
            )
        if reference.url is not None and reference.url != reference.name:
            _print_box_row(
                stream, columns, _escape_text(reference.url), prefix="    ", hang_indent="    "
            )


def print_cve_tty(cve: CVE, stream: TextIO, term_columns: int | None = None) -> None:
    """Write a styled CVE box with escaped data and a consistent display width.

    English descriptions take precedence over the first available language. An
    explicit placeholder represents a record with no descriptions. Widths smaller
    than four columns use four columns so the borders and wide characters fit.
    """
    columns = max(4, get_terminal_size((80, 20)).columns if term_columns is None else term_columns)
    color = SEVERITY_COLORS[cve.severity]
    _print_heading(stream, columns, _escape_text(cve.cve_id), color)
    _print_metadata(cve, stream, columns, color)
    _print_divider(stream, columns)
    _print_box_row(stream, columns, _description(cve), line_pre="\033[3m\033[1m", line_post=RESET)
    _print_references(cve, stream, columns)
    stream.write(f"╚{'═' * (columns - 2)}╝\n")


def print_cve_notty(cve: CVE, stream: TextIO) -> None:
    """Write one tab-separated CVE record with embedded controls escaped."""
    stream.write(f"{_escape_text(cve.cve_id)}\t{_description(cve)}\n")


def _render_blocks(cves: Iterable[CVE], columns: int) -> Iterator[str]:
    for cve in cves:
        buffer = StringIO()
        print_cve_tty(cve, buffer, columns)
        yield buffer.getvalue()


def _write_to_pager(process: Popen[bytes], text: str) -> None:
    if process.stdin is None:
        raise RuntimeError("Cannot render CVEs: the pager has no input pipe")
    process.stdin.write(text.encode("utf-8"))


def _print_with_pager(blocks: Iterator[str], pager: str, rows: int) -> None:
    buffered = []
    line_count = 0
    for block in blocks:
        buffered.append(block)
        line_count += block.count("\n")
        if line_count >= rows:
            break
    else:
        sys.stdout.write("".join(buffered))
        return
    with Popen([pager, "-R"], stdin=PIPE) as process:
        _write_to_pager(process, "".join(buffered))
        for block in blocks:
            _write_to_pager(process, block)


def print_cves(cves: Iterable[CVE], force_color: bool | None = None) -> None:
    """Write safe plain output or styled output, paging when needed."""
    if force_color is None:
        force_color = bool(sys.stdout.isatty() and sys.stderr.isatty())
    if not force_color:
        for cve in cves:
            print_cve_notty(cve, sys.stdout)
        return
    term_size = get_terminal_size((80, 20))
    pager = which("less")
    blocks = _render_blocks(cves, term_size.columns)
    if pager is None:
        for block in blocks:
            sys.stdout.write(block)
    else:
        _print_with_pager(blocks, pager, term_size.lines)
